def _tier_weights(seriousness: int) -> list[float]:
    """本気度(1-5)から各tier(ネタ/普通/ガチ)の選択確率を決める。"""
    table = {
        1: [0.80, 0.15, 0.05],
        2: [0.50, 0.35, 0.15],
        3: [0.20, 0.55, 0.25],
        4: [0.05, 0.35, 0.60],
        5: [0.02, 0.13, 0.85],
    }
    return table[seriousness]


def generate(situation: str, seriousness: int) -> dict:
    """言い訳を1つ生成して dict で返す。"""
    if situation not in REASONS:
        raise ValueError(f"unknown situation: {situation}")
    seriousness = max(1, min(5, seriousness))

    tier = random.choices([1, 2, 3], weights=_tier_weights(seriousness))[0]
    opener, o_mod = random.choice(OPENERS)
    reason, base = random.choice(REASONS[situation][tier])
    closer, c_mod = random.choice(CLOSERS)

    text = f"{opener}{reason}んだ。{closer}"

    # バレ確率 = 理由のヤバさ + 前置き/締めの補正 + 乱数ノイズ
    risk = base + o_mod + c_mod + random.randint(-7, 7)
    risk = max(1, min(99, risk))

    return {
        "text": text,
        "risk": risk,
        "tier": tier,
        "situation": situation,
        "situation_label": SITUATIONS[situation],
        "seriousness": seriousness,
    }


def risk_comment(risk: int) -> str:
    """バレ確率に応じた一言コメント。"""
    if risk < 20:
        return "ほぼ完璧。堂々と送ろう。"
    if risk < 40:
        return "十分通用する。声のトーンだけ気をつけて。"
    if risk < 60:
        return "五分五分。相手の機嫌次第。"
    if risk < 80:
        return "かなり危険。既読無視される覚悟を。"
    return "もはや正直に謝ったほうが早い。"
